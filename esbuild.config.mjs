import esbuild from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import process from "process";
import { builtinModules, createRequire } from "node:module";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the repository of this plugin.
*/
`;

const mode = process.argv[2] ?? "dev";

const nodeEntries = {
	verify: "tests/unit/verify.ts", perf: "benchmarks/perf.ts", sweep: "benchmarks/mmr-sweep.ts",
	"live-review": "tests/live/check-review.ts",
};
const alias = { obsidian: "./tests/support/obsidian-stub.ts" };
if (Object.hasOwn(nodeEntries, mode)) {
	await esbuild.build({ entryPoints: [nodeEntries[mode]], alias, bundle: true, platform: "node", format: "cjs",
		outfile: `.cache/build/${mode}.cjs`, logLevel: "info" });
	process.exit(0);
}

if (mode === "preview") {
	for (const [entry, output] of [["preview/main.ts", "preview/preview.js"], ["preview/embed-main.ts", "preview/embed.js"]]) {
		await esbuild.build({ entryPoints: [entry], alias, bundle: true, platform: "browser", format: "iife", outfile: output, logLevel: "info" });
	}
	process.exit(0);
}

const browserEntries = {
	review: "tests/browser/review.ts", doi: "tests/browser/doi-recovery.ts", maintenance: "tests/browser/maintenance.ts",
};
if (["browser", "review-browser", "doi-browser"].includes(mode)) {
	const directory = ".cache/build/browser";
	mkdirSync(directory, { recursive: true });
	for (const [name, entry] of Object.entries(browserEntries)) {
		if (mode !== "browser" && name !== (mode === "doi-browser" ? "doi" : "review")) continue;
		await esbuild.build({ entryPoints: [entry], alias, bundle: true, platform: "browser", format: "iife", outfile: `${directory}/${name}.js` });
		const html = readFileSync("preview/index.html", "utf8")
			.replace(/href="[^" ]*styles\.css[^" ]*"/, 'href="../../../styles.css"')
			.replace(/<script type="module">[\s\S]*?<\/script>/, `<script src="${name}.js"></script>`)
			.replace(/\r\n/g, "\n");
		writeFileSync(`${directory}/${name}.html`, html);
	}
	process.exit(0);
}

const prod = mode === "production";
if (!prod && mode !== "dev") throw new Error(`Unknown build mode: ${mode}`);

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	// esbuild's CJS wrapper exposes the default class as `.default`.
	// Obsidian expects `module.exports` to be the plugin class itself.
	// This file is not executed under Node (package.json is "type": "module");
	// Obsidian loads it as CommonJS from the vault plugin folder.
	footer: {
		js: "module.exports = module.exports.default;",
	},
});

if (prod) {
	await context.rebuild();
	const source = readFileSync("main.js", "utf8");
	if (!source.includes("module.exports = module.exports.default;")) {
		throw new Error("main.js is missing the Obsidian default-export footer");
	}
	if (/require\(["']electron["']\)/.test(source)) {
		throw new Error('main.js must not contain require("electron")');
	}
	// Desktop-only (manifest isDesktopOnly): Node's file APIs read the research repository's shared
	// provider pauses, and child processes run its research CLI and availability worker
	// (src/research-tools.ts), which writes those pauses and the OpenAlex response cache.
	// Anything else needs an explicit decision here.
	const allowed = new Set(["obsidian", "fs", "path", "child_process"]);
	const requires = [...source.matchAll(/require\(["']([^"']+)["']\)/g)].map((match) => match[1]);
	const foreign = requires.filter((id) => !allowed.has(id));
	if (foreign.length > 0) {
		throw new Error(`main.js may only require ${[...allowed].join(", ")}; found: ${foreign.join(", ")}`);
	}
	class Plugin {}
	class ItemView {}
	class PluginSettingTab {}
	class MarkdownRenderChild {}
	class Modal {}
	class TFile {}
	const obsidian = {
		Plugin,
		ItemView,
		PluginSettingTab,
		MarkdownRenderChild,
		Modal,
		TFile,
		Platform: { isDesktopApp: false },
		requestUrl() {
			return Promise.resolve({ status: 200, json: {} });
		},
		Setting: class Setting {},
	};
	const pluginModule = { exports: {} };
	const load = new Function("module", "exports", "require", source);
	const nodeRequire = createRequire(import.meta.url);
	load(pluginModule, pluginModule.exports, (id) => {
		if (id === "obsidian") return obsidian;
		if (allowed.has(id)) return nodeRequire(id);
		throw new Error(`unexpected require(${id})`);
	});
	if (typeof pluginModule.exports !== "function") {
		throw new Error("main.js must export the plugin class");
	}
	if (!(pluginModule.exports.prototype instanceof Plugin)) {
		throw new Error("main.js export does not extend Plugin");
	}
	await context.dispose();
	process.exit(0);
} else {
	await context.watch();
}
